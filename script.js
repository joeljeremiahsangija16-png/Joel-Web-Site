const languageSelect = document.querySelector('#languageSelect');
const translatedElements = document.querySelectorAll('[data-i18n]');
const supportedLanguages = ['en', 'sw', 'fr', 'es', 'ar', 'de', 'zh', 'pt', 'hi', 'ja', 'it', 'ru', 'tr', 'ko', 'af'];

function setActiveNav(link) {
  const nav = document.querySelector('.main-nav');
  const indicator = nav?.querySelector('.nav-indicator');
  const navLinks = nav ? nav.querySelectorAll('.nav-link') : [];

  if (!nav || !indicator || !link) {
    return;
  }

  navLinks.forEach((navLink) => {
    navLink.classList.toggle('active', navLink === link);
  });

  const navRect = nav.getBoundingClientRect();
  const linkRect = link.getBoundingClientRect();

  indicator.style.width = `${linkRect.width}px`;
  indicator.style.transform = `translateX(${linkRect.left - navRect.left}px)`;
}

function initNavigationTabs() {
  const navLinks = document.querySelectorAll('.nav-link');
  const currentPath = window.location.pathname.split('/').pop() || 'index.html';
  const activeLink = Array.from(navLinks).find((link) => link.getAttribute('href') === currentPath)
    || navLinks[0];

  if (activeLink) {
    setActiveNav(activeLink);
  }

  navLinks.forEach((link) => {
    link.addEventListener('click', () => setActiveNav(link));
  });
}

function initHeroSlider() {
  const slides = document.querySelectorAll('.hero-slide');

  if (slides.length < 2) {
    return;
  }

  let slideIndex = 0;

  const showSlide = (index) => {
    slides.forEach((slide, slidePosition) => {
      slide.classList.toggle('active', slidePosition === index);
    });
  };

  showSlide(slideIndex);

  setInterval(() => {
    slideIndex = (slideIndex + 1) % slides.length;
    showSlide(slideIndex);
  }, 5000);
}

function applyLanguage(lang) {
  const selectedLang = supportedLanguages.includes(lang) ? lang : 'en';
  const selectedText = { ...translations.en, ...(translations[selectedLang] || {}) };

  translatedElements.forEach((element) => {
    const key = element.dataset.i18n;
    if (selectedText[key]) {
      element.textContent = selectedText[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (selectedText[key]) {
      element.placeholder = selectedText[key];
    }
  });

  document.documentElement.lang = selectedLang;
  localStorage.setItem('sdcn_language', selectedLang);

  if (languageSelect) {
    languageSelect.value = selectedLang;
  }
}

if (languageSelect) {
  languageSelect.addEventListener('change', (event) => {
    applyLanguage(event.target.value);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLanguage = localStorage.getItem('sdcn_language') || 'en';
  applyLanguage(savedLanguage);
  initNavigationTabs();
  initHeroSlider();

  window.addEventListener('resize', () => {
    const activeNav = document.querySelector('.nav-link.active');
    if (activeNav) {
      setActiveNav(activeNav);
    }
  });
});

function saveFormSubmission(formName, payload) {
  const existing = JSON.parse(localStorage.getItem('sdcn_form_submissions') || '[]');
  existing.push({
    form: formName,
    submittedAt: new Date().toISOString(),
    ...payload
  });
  localStorage.setItem('sdcn_form_submissions', JSON.stringify(existing));
}

function setupForm(form) {
  const statusBox = form.querySelector('.form-status');

  form.addEventListener('submit', (event) => {
    event.preventDefault();

    const formData = new FormData(form);
    const payload = Object.fromEntries(formData.entries());
    const name = payload.name || 'Customer';
    const formName = form.dataset.form || 'general';

    saveFormSubmission(formName, payload);

    if (statusBox) {
      statusBox.textContent = `Thank you, ${name}! Your request has been received and our team will contact you soon.`;
    }

    const subject = encodeURIComponent(`New ${formName} enquiry from ${name}`);
    const body = encodeURIComponent(
      `Name: ${payload.name || ''}\nPhone: ${payload.phone || ''}\nEmail: ${payload.email || ''}\nLocation: ${payload.area || ''}\nVehicle: ${payload.vehicle || ''}\nService: ${payload.service || ''}\nDetails: ${payload.details || payload.message || ''}`
    );

    if (typeof window !== 'undefined') {
      window.location.href = `mailto:hello@sdcn.co.tz?subject=${subject}&body=${body}`;
    }

    form.reset();
  });
}

document.querySelectorAll('form[data-form]').forEach(setupForm);
